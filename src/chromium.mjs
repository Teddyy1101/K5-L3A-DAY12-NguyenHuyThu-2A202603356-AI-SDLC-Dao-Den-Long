import { spawn } from 'node:child_process';
import { existsSync } from 'node:fs';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

export const delay=(ms)=>new Promise((resolve)=>setTimeout(resolve,ms));

function browserPath() {
  if (process.env.CHROME_PATH) return process.env.CHROME_PATH;
  const names=process.platform==='win32'
    ? ['C:/Program Files/Google/Chrome/Application/chrome.exe',
      'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe']
    : process.platform==='darwin'
      ? ['/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
        '/Applications/Chromium.app/Contents/MacOS/Chromium']
      : ['/usr/bin/google-chrome','/usr/bin/chromium','/usr/bin/chromium-browser','/snap/bin/chromium'];
  const path=names.find(existsSync);
  if (!path) throw Error('Cần Chrome hoặc Chromium. Đặt CHROME_PATH tới tệp thực thi nếu dùng đường dẫn riêng.');
  return path;
}

export async function openChromium(url) {
  const executable=browserPath();
  const profile=await mkdtemp(join(tmpdir(),'dao-den-long-browser-'));
  const flags=['--no-first-run','--disable-background-networking','--remote-debugging-port=0',
    '--window-size=1280,720','--force-device-scale-factor=1','--disable-background-timer-throttling',
    '--disable-renderer-backgrounding','--user-data-dir='+profile];
  if (process.env.BENCH_HEADLESS==='1') flags.push('--headless');
  if (process.env.BENCH_SOFTWARE==='1') flags.push('--disable-gpu');
  const child=spawn(executable,[...flags,url],{stdio:['ignore','ignore','pipe'],windowsHide:true});
  let failure, socket, stderr='';
  child.once('error',(error)=>{failure=error;});
  child.stderr.on('data',(chunk)=>{stderr=(stderr+chunk).slice(-1600);});
  const close=async()=>{
    socket?.close();
    if (child.pid && child.exitCode===null && child.signalCode===null) {
      const exited=new Promise((resolve)=>child.once('exit',resolve));
      child.kill();
      await Promise.race([exited,delay(2000)]);
    }
    // Chrome's own profile was generated by mkdtemp and lives under the system temp directory.
    if (process.platform!=='win32') await rm(profile,{recursive:true,force:true}).catch(()=>{});
  };
  try {
    let port;
    for (let tries=0; tries<150 && !port; tries++) {
      if (failure) throw failure;
      if (child.exitCode!==null) throw Error(stderr);
      try { port=(await readFile(join(profile,'DevToolsActivePort'),'utf8')).split('\n')[0]; }
      catch { await delay(75); }
    }
    if (!port) throw Error('Chrome không khởi động được. '+stderr);
    const pages=await (await fetch('http://127.0.0.1:'+port+'/json/list')).json();
    const page=pages.find((item)=>item.type==='page');
    if (!page) throw Error('Không tìm thấy trang benchmark.');
    socket=new WebSocket(page.webSocketDebuggerUrl);
    await new Promise((resolve,reject)=>{socket.onopen=resolve;socket.onerror=reject;});
    let sequence=0;
    const pending=new Map();
    socket.onmessage=({data})=>{
      const reply=JSON.parse(data);
      const task=pending.get(reply.id);
      if (!task) return;
      clearTimeout(task.timeout);
      pending.delete(reply.id);
      if (reply.error) task.reject(Error(reply.error.message)); else task.resolve(reply.result);
    };
    const send=(method,params={})=>new Promise((resolve,reject)=>{
      const id=++sequence;
      const timeout=setTimeout(()=>{pending.delete(id);reject(Error('Chrome: '+method+' timed out'));},15000);
      pending.set(id,{resolve,reject,timeout});
      socket.send(JSON.stringify({id,method,params}));
    });
    const evaluate=async(expression)=>{
      const result=await send('Runtime.evaluate',{expression,awaitPromise:true,returnByValue:true});
      if (result.exceptionDetails) throw Error(result.exceptionDetails.exception?.description ?? result.exceptionDetails.text);
      return result.result.value;
    };
    await send('Emulation.setDeviceMetricsOverride',{width:1280,height:720,deviceScaleFactor:1,mobile:false});
    return {send,evaluate,close};
  } catch (error) { await close(); throw error; }
}
